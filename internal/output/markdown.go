package output

import (
	"bytes"
	"fmt"
	"io"
	"os"
	"strings"
	"time"
)

// WriteMarkdown renders doc as a Markdown report.
func WriteMarkdown(w io.Writer, doc Document) error {
	doc = doc.normalized()
	b := &bufw{w: w}
	b.f("<!-- generated by sre %s; do not edit by hand -->\n\n", doc.Command)
	b.f("# %s\n\n", inline(doc.Title))
	if !doc.GeneratedAt.IsZero() {
		b.f("- **Generated:** %s\n", doc.GeneratedAt.UTC().Format(time.RFC3339))
	}
	if doc.Demo {
		b.f("- **Mode:** demo\n")
	}
	for _, f := range doc.Meta {
		b.f("- **%s:** %s\n", inline(f.Name), inline(f.Value))
	}
	if len(doc.Summary) > 0 {
		b.f("\n## Summary\n\n")
		for _, c := range doc.Summary {
			b.f("- %s: %d\n", inline(c.Name), c.Count)
		}
	}
	if len(doc.Summary) > 0 || len(doc.Findings) > 0 {
		b.f("\n## Findings\n\n")
		if len(doc.Findings) == 0 {
			b.f("No findings in this scope.\n")
		}
		for i, f := range doc.Findings {
			b.f("### %d. %s · %s · %s\n\n", i+1, strings.ToUpper(f.Severity), inline(f.Category), inline(f.Resource))
			b.f("- **Phenomenon:** %s\n", inline(f.Phenomenon))
			b.f("- **Likely cause:** %s\n", inline(f.LikelyCause))
			b.f("- **Next step:** %s\n", inline(f.NextStep))
			for _, d := range f.Details {
				b.f("- **%s:** %s\n", inline(d.Name), inline(d.Value))
			}
			b.f("\n")
		}
	}
	if len(doc.Notes) > 0 {
		b.f("## Notes\n\n")
		for _, n := range doc.Notes {
			b.f("- %s\n", inline(n))
		}
	}
	return b.err
}

// WriteMarkdownFile writes a Markdown report to path, replacing an existing file.
func WriteMarkdownFile(path string, doc Document) error {
	if strings.TrimSpace(path) == "" || path == "-" {
		return fmt.Errorf("report path must be a file path")
	}
	var buf bytes.Buffer
	if err := WriteMarkdown(&buf, doc); err != nil {
		return err
	}
	if err := os.WriteFile(path, buf.Bytes(), 0o644); err != nil {
		return fmt.Errorf("write report %s: %w", path, err)
	}
	return nil
}

func inline(s string) string {
	s = strings.ReplaceAll(s, "\r\n", " ")
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "\r", " ")
	return strings.Join(strings.Fields(s), " ")
}
